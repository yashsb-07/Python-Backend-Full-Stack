/* 1. Find frequency of each character in a string */

let str = "helloyash";

let freq = {};

for (let char of str){
    if (freq[char]){
        freq[char]++;
    } else {
        freq[char] = 1;
    }
}

console.log(freq);

/* 2. Sort array without using .sort() */

let arr = [5, 3, 8, 4, 2];

for (let i = 0; i < arr.length; i++) {
    for (let j = 0; j < arr.length - 1; j++) {
        if (arr[j] > arr[j + 1]) {
            // swapg
            let temp = arr[j];
            arr[j] = arr[j + 1];
            arr[j + 1] = temp;
        }
    }
}

console.log(arr);

